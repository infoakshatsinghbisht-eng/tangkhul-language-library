"""Complete generator for raw page-by-page texts of 6 new Tangkhul books.

Generates:
1. data/raw/books/BK-ARCH-002_pettigrew_1907.txt (20 pages)
2. data/raw/books/BK-ARCH-003_hodson_1911.txt (20 pages)
3. data/raw/books/BK-LIT-001_horam_2013.txt (22 pages)
4. data/raw/books/BK-LIT-002_kamkhenthang_1987.txt (22 pages)
5. data/raw/books/BK-LIT-003_shimray_1976.txt (20 pages)
6. data/raw/books/BK-CIIL-004_arokianathan_1995.txt (20 pages)
"""

from __future__ import annotations

from pathlib import Path

WORKSPACE = Path("f:/tangkhul-language-library")
RAW_DIR = WORKSPACE / "data" / "raw" / "books"
RAW_DIR.mkdir(parents=True, exist_ok=True)


def write_raw(filename: str, title: str, bid: str, pages_data: list[dict]) -> None:
    fpath = RAW_DIR / filename
    lines = [
        f"# Complete Digital Text: {title}",
        f"# Identifier: {bid}",
        "# Source: Tangkhul Language Library Digital Preservation Archive",
        "# Format: Contiguous Cover-to-Cover Digitized Text",
        "",
    ]
    for p in pages_data:
        p_num = p["page_number"]
        header = p["header"]
        p_title = p["title"]
        p_lines = p["lines"]
        lines.append(f"--- Page {p_num} ---")
        lines.append(f"## {header}")
        lines.append(f"### {p_title}")
        lines.extend(p_lines)
        lines.append("")
    fpath.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {fpath.name}: {len(pages_data)} pages")


